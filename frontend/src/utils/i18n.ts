const localeMessages: Record<AppLocale, Record<MessageKey, string>> = {
  ...messages,
  'ja-JP': jaMessages,
  'ko-KR': koMessages,
  'ru-RU': ruMessages,
};

const isAppLocale = (value: string | null): value is AppLocale => (
  value === 'zh-CN' || value === 'zh-TW' || value === 'en-US' || value === 'ja-JP' || value === 'ko-KR' || value === 'ru-RU'
);

const getInitialLocale = (): AppLocale => {
  if (typeof localStorage === 'undefined') return 'zh-CN';
  const storedLocale = localStorage.getItem(LOCALE_STORAGE_KEY);
  return isAppLocale(storedLocale) ? storedLocale : 'zh-CN';
};

export const currentLocale = ref<AppLocale>(getInitialLocale());

export const localeOptions = [
  { value: 'zh-CN' as const, labelKey: 'language.zhCN', shortLabel: '简' },
  { value: 'zh-TW' as const, labelKey: 'language.zhTW', shortLabel: '繁' },
  { value: 'en-US' as const, labelKey: 'language.enUS', shortLabel: 'EN' },
  { value: 'ja-JP' as const, labelKey: 'language.jaJP', shortLabel: '日' },
  { value: 'ko-KR' as const, labelKey: 'language.koKR', shortLabel: '한' },
  { value: 'ru-RU' as const, labelKey: 'language.ruRU', shortLabel: 'РУ' },
] as const;

export const currentLocaleOption = computed(() => (
  localeOptions.find((option) => option.value === currentLocale.value) || localeOptions[0]
));

export const t = (key: MessageKey) => {
  return localeMessages[currentLocale.value][key] || messages['zh-CN'][key] || key;
};

export const setLocale = (locale: AppLocale) => {
  currentLocale.value = locale;
  localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new CustomEvent('weather-locale-change', { detail: { locale } }));
};

export const initLocale = () => {
  document.documentElement.lang = currentLocale.value;
};
